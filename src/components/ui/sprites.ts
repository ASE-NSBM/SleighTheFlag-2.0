export type SpriteName = keyof typeof SPRITES;

/* ───────────────────────────── rendering ────────────────────────────── */

export interface CompiledSprite {
  size: number;
  /** One SVG path per colour (horizontal runs merged into rectangles). */
  layers: { color: string; d: string }[];
}

const cache = new Map<string, CompiledSprite>();

export function compileSprite(name: SpriteName): CompiledSprite {
  const cached = cache.get(name);
  if (cached) return cached;

  const rows: string[] = SPRITES[name];
  const paths = new Map<string, string>();

  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const char = row[x];
      let run = 1;
      while (x + run < row.length && row[x + run] === char) run++;
      if (char !== ".") {
        const color = PALETTE[char] ?? "#ff00ff"; // loud magenta = typo in the art
        paths.set(color, `${paths.get(color) ?? ""}M${x} ${y}h${run}v1h-${run}z`);
      }
      x += run;
    }
  });

  const compiled: CompiledSprite = {
    size: rows.length,
    layers: [...paths].map(([color, d]) => ({ color, d })),
  };
  cache.set(name, compiled);
  return compiled;
}
